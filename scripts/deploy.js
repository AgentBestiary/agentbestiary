// Production deploy: NFT + market on BSC, then writes addresses into web/config.js and web/llms.txt
const fs = require("fs");
const path = require("path");
const crypto = require("crypto");
const { ethers } = require("hardhat");

const REGISTRY = "0x60B9262456dE011F7d15a54CdD8c48bAaa8B022F";
const PRICE = ethers.parseEther("0.0003");
const REVEAL_DELAY_BLOCKS = Number(process.env.REVEAL_DELAY_BLOCKS || 200); // ~10 min on BSC

const WEB_CONFIG = path.join(__dirname, "..", "web", "config.js");
const LLMS = path.join(__dirname, "..", "web", "llms.txt");
const SECRET_FILE = path.join(process.env.HOME, ".bestiary-secret.json");

async function main() {
  const [deployer] = await ethers.getSigners();
  const treasury = process.env.TREASURY || "0x76567BeFC21816f1e2D7Cb2b5c9e0a5D37a5D4a0";
  const bal = await ethers.provider.getBalance(deployer.address);
  console.log("deployer:", deployer.address, "| balance:", ethers.formatEther(bal), "BNB");
  if (bal === 0n) throw new Error("deployer wallet has no BNB for gas");

  // commit-reveal secret: random 32 bytes, saved locally, only the hash goes on-chain
  const secret = "0x" + crypto.randomBytes(32).toString("hex");
  const commitment = ethers.keccak256(ethers.solidityPacked(["bytes32"], [secret]));
  fs.writeFileSync(SECRET_FILE, JSON.stringify({ secret, commitment, createdAt: new Date().toISOString() }, null, 2));
  fs.chmodSync(SECRET_FILE, 0o600);

  const head = await ethers.provider.getBlockNumber();
  const revealBlock = head + REVEAL_DELAY_BLOCKS;

  console.log("registry:", REGISTRY);
  console.log("treasury:", treasury);
  console.log("price:", ethers.formatEther(PRICE), "BNB");
  console.log("commitment:", commitment);
  console.log("revealBlock:", revealBlock, `(+${REVEAL_DELAY_BLOCKS} blocks, head ${head})`);

  const Bestiary = await ethers.getContractFactory("AgentBestiary");
  const nft = await Bestiary.deploy(REGISTRY, treasury, PRICE, revealBlock, commitment);
  await nft.waitForDeployment();
  const nftAddr = await nft.getAddress();
  const nftTx = nft.deploymentTransaction();
  console.log("NFT deployed:", nftAddr, "tx", nftTx.hash);

  const Market = await ethers.getContractFactory("BestiaryMarket");
  const market = await Market.deploy(nftAddr, treasury);
  await market.waitForDeployment();
  const mkAddr = await market.getAddress();
  console.log("Market deployed:", mkAddr, "tx", market.deploymentTransaction().hash);

  // sanity reads
  console.log("MAX_SUPPLY:", (await nft.MAX_SUPPLY()).toString());
  console.log("MAX_PER_WALLET:", (await nft.MAX_PER_WALLET()).toString());
  console.log("FREE_QUOTA:", (await nft.FREE_QUOTA()).toString());

  // write front-end config
  const cfg = `// Generated by scripts/deploy.js on ${new Date().toISOString()}
window.BESTIARY_CONFIG = {
  chainId: 56,
  chainName: "BNB Smart Chain",
  rpc: "https://bsc-dataseed.bnbchain.org",
  explorer: "https://bscscan.com",
  registry: "${REGISTRY}",
  nft: "${nftAddr}",
  market: "${mkAddr}",
  wcProjectId: "5e2f89a9606073fc5f4e3713925259c7",
  launched: false
};`;
  fs.writeFileSync(WEB_CONFIG, cfg);

  // fill the agent guide with real addresses
  let llms = fs.readFileSync(LLMS, "utf8");
  llms = llms.split("__NFT__").join(nftAddr).split("__MARKET__").join(mkAddr);
  fs.writeFileSync(LLMS, llms);

  fs.writeFileSync(
    path.join(__dirname, "..", "deployment.json"),
    JSON.stringify({ nft: nftAddr, market: mkAddr, treasury, registry: REGISTRY, price: PRICE.toString(), revealBlock, commitment, deployedAt: new Date().toISOString() }, null, 2)
  );

  console.log("\nsecret saved to", SECRET_FILE, "(0600). Keep it: reveal needs it.");
  console.log("config + llms.txt updated.");
}

main().catch((e) => { console.error(e); process.exit(1); });
